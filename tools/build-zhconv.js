// Builds lang/zh/zhconv.js (Simplified <-> Traditional character tables) from OpenCC's
// STCharacters.txt and TSCharacters.txt (https://github.com/BYVoid/OpenCC, Apache-2.0,
// see lang/zh/OPENCC-LICENSE.txt). Used by lang/zh/lookup.js to look words up in 萌典, which only
// knows Traditional characters, and to show its definitions in Simplified.
//   node tools/build-zhconv.js <dir containing STCharacters.txt and TSCharacters.txt>
const fs = require("fs");
const path = require("path");

const src = process.argv[2];
if (!src) throw new Error("usage: node tools/build-zhconv.js <opencc dictionary dir>");

// "key<TAB>value1 value2 ..." -> { key: "value1 value2" }; the first value is the usual one.
function read(file) {
  const map = {};
  for (const line of fs.readFileSync(path.join(src, file), "utf8").split(/\r?\n/)) {
    if (!line || line.startsWith("#")) continue;
    const [key, values] = line.split("\t");
    if (key && values) map[key] = values.trim();
  }
  return map;
}

const s2t = read("STCharacters.txt");
const t2s = read("TSCharacters.txt");
const out = `// Generated by tools/build-zhconv.js from OpenCC (Apache-2.0, see OPENCC-LICENSE.txt). Do not edit.
// Character -> space-separated candidates, most common first.
const ZH_S2T = ${JSON.stringify(s2t)};
const ZH_T2S = ${JSON.stringify(t2s)};
if (typeof module !== "undefined" && module.exports) module.exports = { ZH_S2T, ZH_T2S };
`;
fs.writeFileSync(path.join(__dirname, "..", "lang", "zh", "zhconv.js"), out);
console.log(`S->T: ${Object.keys(s2t).length}, T->S: ${Object.keys(t2s).length}, file: ${Buffer.byteLength(out)} bytes`);
