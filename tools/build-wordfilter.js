// Builds lang/en/wordfilter.js (a Bloom filter of lang/en/words.txt) so the content script can check words
// instantly, without waking the background service worker. Re-run after changing lang/en/words.txt:
//   node tools/build-wordfilter.js
// False-positive rate is about 1 in 1000: a made-up word occasionally passes, which only means
// it gets &tbs=1. Hashing must match wordFilterHas() in lang/en/lang.js.
const fs = require("fs");
const path = require("path");

const dir = path.join(__dirname, "..", "lang", "en");
const words = fs.readFileSync(path.join(dir, "words.txt"), "utf8").split("\n").filter(Boolean);

const n = words.length;
const p = 0.001;
const m = Math.ceil((-n * Math.log(p)) / Math.LN2 ** 2);
const k = Math.round((m / n) * Math.LN2);

function fnv1a(s, seed) {
  let h = seed >>> 0;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 16777619) >>> 0;
  }
  return h;
}

const bits = new Uint8Array(Math.ceil(m / 8));
for (const w of words) {
  const h1 = fnv1a(w, 2166136261);
  const h2 = fnv1a(w, 3735928559) | 1;
  for (let i = 0; i < k; i++) {
    const b = (h1 + Math.imul(i, h2)) >>> 0;
    const idx = b % m;
    bits[idx >> 3] |= 1 << (idx & 7);
  }
}

// Each character holds 6 filter bits (bit i of the filter is bit i % 6 of character i / 6), so the
// content script reads bits straight from the string with no decode step on page load.
const ALPHABET = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz-_";
let chars = "";
for (let c = 0; c < Math.ceil(m / 6); c++) {
  let v = 0;
  for (let j = 0; j < 6; j++) {
    const idx = c * 6 + j;
    if (idx < m && bits[idx >> 3] & (1 << (idx & 7))) v |= 1 << j;
  }
  chars += ALPHABET[v];
}

const out = `// Generated by tools/build-wordfilter.js from words.txt (${n} words). Do not edit.
// Bloom filter: m bits, k hashes; 6 bits per character of \`bits\`. Checked by wordFilterHas() in lang/en/lang.js.
"use strict";
const WORD_FILTER = { m: ${m}, k: ${k}, alphabet: "${ALPHABET}", bits: "${chars}" };
if (typeof module !== "undefined" && module.exports) module.exports = WORD_FILTER;
`;
fs.writeFileSync(path.join(dir, "wordfilter.js"), out);
console.log(`words: ${n}, m: ${m} bits (${bits.length} bytes), k: ${k}, file: ${out.length} bytes`);
